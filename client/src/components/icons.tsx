/**
 * Inline brand glyphs.
 *
 * The installed lucide-react (v1.25) no longer ships every brand mark, and
 * brand logos are trademarked anyway — drawing the ones we need as tiny inline
 * SVGs keeps the icon set complete without adding a dependency.
 *
 * Two families live here:
 *  - `*Icon` (outline, stroke-based) — used beside a visible text label in the
 *    contact rows and footer, where a lighter weight reads better.
 *  - `*Glyph` (solid, fill-based) — the standard monochrome brand marks used in
 *    the icon-only social carousel, where the shape has to carry the meaning on
 *    its own.
 *
 * Every glyph paints with `currentColor`, so a single text-colour utility
 * themes it, and every one is decorative (`aria-hidden`) because each is always
 * paired with an accessible name on its link.
 */
